def shade(cell,color):
    pr=cell._tc.get_or_add_tcPr(); x=pr.find(qn('w:shd'))
    if x is None: x=OxmlElement('w:shd'); pr.append(x)
    x.set(qn('w:fill'),color)
def borders(t):
    pr=t._tbl.tblPr; b=pr.find(qn('w:tblBorders'))
    if b is None: b=OxmlElement('w:tblBorders'); pr.append(b)
    for k in ('top','left','bottom','right','insideH','insideV'):
        x=OxmlElement(f'w:{k}'); x.set(qn('w:val'),'single'); x.set(qn('w:sz'),'4'); x.set(qn('w:color'),LINE); b.append(x)
def repeat(row):
    p=row._tr.get_or_add_trPr(); x=OxmlElement('w:tblHeader'); x.set(qn('w:val'),'true'); p.append(x)
def table(doc, headers, rows, widths=None, font=8.2):
    t=doc.add_table(rows=1,cols=len(headers)); t.alignment=WD_TABLE_ALIGNMENT.CENTER; t.autofit=False
    for i,v in enumerate(headers):
        c=t.rows[0].cells[i]; c.text=str(v); shade(c,NAV); c.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
        for r in c.paragraphs[0].runs: r.font.bold=True; r.font.color.rgb=RGBColor(255,255,255); r.font.size=Pt(font)
    repeat(t.rows[0])
    for ri,row in enumerate(rows):
        cs=t.add_row().cells
        for i,v in enumerate(row):
            cs[i].text='' if v is None else str(v); cs[i].vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            if ri%2: shade(cs[i],PALE)
            for p in cs[i].paragraphs:
                p.paragraph_format.space_after=Pt(1); p.paragraph_format.line_spacing=1.05
                for r in p.runs: r.font.name='Microsoft YaHei'; r.font.size=Pt(font)
    if widths:
        for row in t.rows:
            for i,w in enumerate(widths): row.cells[i].width=Cm(w)
    borders(t); doc.add_paragraph().paragraph_format.space_after=Pt(2); return t
def para(doc,text='',lead=None,fill=None):
    p=doc.add_paragraph(); p.paragraph_format.space_after=Pt(5); p.paragraph_format.line_spacing=1.25
    if lead: p.add_run(lead).bold=True
    p.add_run(text)
    if fill:
        pr=p._p.get_or_add_pPr(); x=OxmlElement('w:shd'); x.set(qn('w:fill'),fill); pr.append(x)
    return p
def bullets(doc,items):
    for x in items:
        p=doc.add_paragraph(style='List Bullet'); p.paragraph_format.space_after=Pt(2); p.add_run(x)
def head(doc,text,level=1):
    p=doc.add_heading(text,level=level); p.paragraph_format.keep_with_next=True; return p
def toc(doc):
    p=doc.add_paragraph(); r=p.add_run(); f=OxmlElement('w:fldSimple'); f.set(qn('w:instr'),'TOC \\o "1-3" \\h \\z \\u'); r._r.addnext(f)
def setup():
    d=Document(); s=d.sections[0]; s.top_margin=Cm(1.8); s.bottom_margin=Cm(1.7); s.left_margin=Cm(1.9); s.right_margin=Cm(1.9)
    for n,z in [('Normal',10),('Title',25),('Subtitle',12),('Heading 1',18),('Heading 2',14),('Heading 3',11.5)]:
        st=d.styles[n]; st.font.name='Microsoft YaHei'; st._element.rPr.rFonts.set(qn('w:eastAsia'),'Microsoft YaHei'); st.font.size=Pt(z); st.font.color.rgb=RGBColor(0,0,0)
        if n.startswith('Heading'): st.font.bold=True; st.paragraph_format.space_before=Pt(9); st.paragraph_format.space_after=Pt(4); st.paragraph_format.keep_with_next=True
    return d

