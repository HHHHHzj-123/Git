def tid(): return str(uuid.uuid4())
def topic(title, children=None, note=None):
    t={'id':tid(),'class':'topic','title':title}
    if children: t['children']={'attached':[topic(c[0],c[1] if len(c)>1 else None,c[2] if len(c)>2 else None) if isinstance(c,tuple) else topic(c) for c in children]}
    if note: t['notes']={'plain':{'content':note}}
    return t
def node(title, children): return (title, children)

