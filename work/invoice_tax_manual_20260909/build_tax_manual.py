def flow_image(name, title, steps, note=""):
    w = 1500; boxw = 215; boxh = 76; gap = 36; margin = 45
    cols = 5; rows = (len(steps)+cols-1)//cols
    h = 120 + rows*150 + 70
    im = Image.new("RGB", (w,h), "white"); d = ImageDraw.Draw(im)
    d.text((margin,25), title, fill=(0,0,0), font=font(34))
    for i,s in enumerate(steps):
        row=i//cols; pos=i%cols
        actual_pos=pos if row%2==0 else cols-1-pos
        x=margin+actual_pos*(boxw+gap); y=95+row*150
        d.rounded_rectangle((x,y,x+boxw,y+boxh),radius=12,fill=(234,242,248),outline=(23,54,93),width=3)
        lines=[]; cur=""
        for ch in s:
            if len(cur)>=10: lines.append(cur); cur=ch
            else: cur+=ch
        if cur: lines.append(cur)
        yy=y+12
        for ln in lines[:2]:
            bbox=d.textbbox((0,0),ln,font=font(22)); d.text((x+(boxw-(bbox[2]-bbox[0]))/2,yy),ln,fill=(0,0,0),font=font(22)); yy+=28
        if i < len(steps)-1:
            if pos < cols-1:
                nx = x+boxw+5 if row%2==0 else x-31
                d.line((nx,y+boxh/2,nx+25*(1 if row%2==0 else -1),y+boxh/2),fill=(47,117,181),width=4)
            else:
                d.line((x+boxw/2,y+boxh+5,x+boxw/2,y+boxh+55),fill=(47,117,181),width=4)
    if note: d.text((margin,h-42),note,fill=(90,90,90),font=font(20))
    path=ASSETS/f"{name}.png"; im.save(path); return path

