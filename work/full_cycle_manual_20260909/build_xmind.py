def uid():
    return secrets.token_hex(12)

def topic(title, children=None, note=None):
    t = {"id": uid(), "class": "topic", "title": title}
    if children:
        t["children"] = {"attached": [topic(*c) if isinstance(c, tuple) else topic(c) for c in children]}
    if note:
        t["notes"] = {"plain": {"content": note}}
    return t

def sheet(title, root_title, branches, structure="org.xmind.ui.map.unbalanced"):
    return {
        "id": uid(), "class": "sheet", "title": title,
        "rootTopic": topic(root_title, branches),
        "topicPositioning": "fixed",
        "structureClass": structure,
    }

