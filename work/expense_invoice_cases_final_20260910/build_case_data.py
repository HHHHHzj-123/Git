def risk_for(cat,title):
    if cat=='RED' or '没有真实业务' in title or '找别人发票' in title: return '红色'
    if cat=='BOSS' and any(k in title for k in ['避孕套','情人','私人住宅','信用卡','学费']): return '红色'
    if cat in ('BOSS','PAY') or any(k in title for k in ['高档酒','购物卡','客户负责人','重复','票货','票款','税率','金额错误','拒绝开票','注销']): return '橙色'
    if cat in ('WEL','MKT','NOP','INV','ASSET'): return '黄色'
    return '蓝色/黄色'

