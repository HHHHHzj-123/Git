def frag(builder):
    d=ap.setup(); builder(d); return [deepcopy(x) for x in list(d.element.body) if x.tag!=qn('w:sectPr')]
def ptext(el):
    return ''.join(t.text or '' for t in el.findall('.//'+qn('w:t'))).strip()
def split_at(blocks,prefix):
    for i,x in enumerate(blocks):
        if x.tag==qn('w:p') and ptext(x).startswith(prefix): return blocks[:i],blocks[i:]
    raise ValueError(prefix)
def find_heading(doc,prefix):
    for p in doc.paragraphs:
        if p.text.strip().startswith(prefix): return p
    raise ValueError(prefix)
def insert_before(doc,prefix,blocks):
    a=find_heading(doc,prefix)._p
    for x in blocks:a.addprevious(x)
def insert_before_prior_page_break(doc,prefix,blocks):
    a=find_heading(doc,prefix)._p; p=a.getprevious(); br=None
    while p is not None:
        if p.findall('.//'+qn('w:br')):br=p;break
        p=p.getprevious()
    a=br or a
    for x in blocks:a.addprevious(x)

